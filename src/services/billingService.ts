import prisma from '../config/prisma';

export const DEFAULT_RATE = 299;
export const STANDARD_RATE = 599;
export const BILLING_START = '2026-10'; // platform billing starts from October 2026 (auto-generation never goes earlier)

// IST month boundaries — "2026-10" => [2026-10-01 00:00 IST, 2026-11-01 00:00 IST)
const IST = '+05:30';
export const monthStart = (ym: string) => new Date(`${ym}-01T00:00:00${IST}`);
export const nextMonth = (ym: string) => { const [y, m] = ym.split('-').map(Number); return m === 12 ? `${y + 1}-01` : `${y}-${String(m + 1).padStart(2, '0')}`; };
export const monthEnd = (ym: string) => new Date(monthStart(nextMonth(ym)).getTime() - 1);
export const monthsBetween = (from: string, to: string): string[] => { const out: string[] = []; let c = from; while (c <= to && out.length < 36) { out.push(c); c = nextMonth(c); } return out; };
export const prevMonthOf = (d = new Date()) => { const ist = new Date(d.getTime() + 330 * 60000); const y = ist.getUTCFullYear(), m = ist.getUTCMonth() + 1; return m === 1 ? `${y - 1}-12` : `${y}-${String(m - 1).padStart(2, '0')}`; };
const monthLabel = (ym: string) => new Date(`${ym}-15T00:00:00Z`).toLocaleString('en-GB', { month: 'long', year: 'numeric', timeZone: 'UTC' });
const dmy = (d: Date) => new Date(d.getTime() + 330 * 60000).toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric', timeZone: 'UTC' });

/** Users of the org who did anything in [start,end]: logged interactions, changed leads, or have audit-log entries. Includes users deactivated later. */
export async function activeUsersForMonth(organisationId: string, ym: string) {
    const s = monthStart(ym), e = new Date(monthStart(nextMonth(ym)).getTime());
    const rows: any[] = await prisma.$queryRawUnsafe(
        `SELECT u.id, u."firstName", u."lastName", u.email, u.role, u."isActive", u."isDeleted" FROM "User" u
         WHERE u."organisationId" = $1 AND u."createdAt" < $3 AND (
           EXISTS (SELECT 1 FROM "Interaction" i WHERE i."createdById" = u.id AND i."organisationId" = $1 AND i."createdAt" >= $2 AND i."createdAt" < $3)
           OR EXISTS (SELECT 1 FROM "LeadHistory" h WHERE h."changedById" = u.id AND h."createdAt" >= $2 AND h."createdAt" < $3)
           OR EXISTS (SELECT 1 FROM "AuditLog" a WHERE a."actorId" = u.id AND a."organisationId" = $1 AND a."createdAt" >= $2 AND a."createdAt" < $3)
         ) ORDER BY u."firstName"`, organisationId, s, e);
    return rows.map((r) => ({ id: r.id, name: `${r.firstName || ''} ${r.lastName || ''}`.trim() || r.email, email: r.email, role: r.role, active: r.isActive && !r.isDeleted }));
}

async function nextInvoiceNumber(ym: string) {
    const prefix = `PYPE-${ym.replace('-', '')}-`;
    const n = await prisma.billingInvoice.count({ where: { invoiceNumber: { startsWith: prefix } } });
    return `${prefix}${String(n + 1).padStart(3, '0')}`;
}

export async function previewInvoice(organisationId: string, from: string, to: string, rateOverride?: number) {
    const org = await prisma.organisation.findUnique({ where: { id: organisationId }, select: { id: true, name: true, billingRate: true } });
    if (!org) throw new Error('Organisation not found');
    const rate = rateOverride ?? org.billingRate ?? DEFAULT_RATE;
    const lines: any[] = [];
    for (const ym of monthsBetween(from, to)) {
        const userList = await activeUsersForMonth(organisationId, ym);
        lines.push({ month: ym, label: monthLabel(ym), start: monthStart(ym), end: monthEnd(ym), users: userList.length, rate, amount: userList.length * rate, userList });
    }
    const subtotal = lines.reduce((a, l) => a + l.amount, 0);
    return { organisation: org, rate, lines, subtotal, total: subtotal };
}

/** Creates one invoice for [from..to] (inclusive months). Returns null if nothing billable or it already exists. */
export async function createInvoice(opts: { organisationId: string; from: string; to: string; rate?: number; auto?: boolean; skipEmpty?: boolean }) {
    const { organisationId, from, to } = opts;
    const periodStart = monthStart(from), periodEnd = monthEnd(to);
    const dup = await prisma.billingInvoice.findFirst({ where: { organisationId, periodStart, periodEnd } });
    if (dup) return { skipped: 'exists' as const, invoice: dup };
    const pv = await previewInvoice(organisationId, from, to, opts.rate);
    if (opts.skipEmpty && pv.total === 0) return { skipped: 'no-active-users' as const };
    const issue = new Date();
    const invoice = await prisma.billingInvoice.create({
        data: {
            invoiceNumber: await nextInvoiceNumber(to), organisationId, periodStart, periodEnd, months: pv.lines.length,
            ratePerUser: pv.rate, standardRate: STANDARD_RATE, subtotal: pv.subtotal, total: pv.total, lines: pv.lines as any,
            dueDate: new Date(issue.getTime() + 7 * 86400000), autoGenerated: !!opts.auto
        }
    });
    return { invoice };
}

/** 1st of each month: invoice the previous month for every billable org. */
export async function generatePreviousMonthInvoices(auto = true) {
    const ym = prevMonthOf();
    if (ym < BILLING_START) return { month: ym, created: 0, skipped: 0 };
    const orgs = await prisma.organisation.findMany({ where: { isDeleted: false, billingEnabled: true, status: { not: 'deleted' } }, select: { id: true } });
    let created = 0, skipped = 0;
    for (const o of orgs) {
        try { const r = await createInvoice({ organisationId: o.id, from: ym, to: ym, auto, skipEmpty: true }); if ((r as any).invoice && !(r as any).skipped) created++; else skipped++; }
        catch (e: any) { skipped++; console.error('[Billing] failed for org', o.id, e.message); }
    }
    return { month: ym, created, skipped };
}
export { dmy, monthLabel };
